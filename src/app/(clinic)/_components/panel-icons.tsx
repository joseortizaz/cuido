import type { ReactNode } from "react";

/**
 * Íconos de línea del panel (menú lateral y encabezados). SVG propios, sin dependencias: trazo de 2 px,
 * `currentColor`, decorativos (`aria-hidden`) porque siempre van junto a un texto.
 */

function Icon({ className, children }: { className?: string; children: ReactNode }) {
  return (
    <svg
      aria-hidden="true"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className ?? "h-5 w-5"}
    >
      {children}
    </svg>
  );
}

